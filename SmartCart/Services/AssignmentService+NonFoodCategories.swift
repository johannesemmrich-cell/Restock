    /// Längstes Stichwort der Warenkunde im (kleingeschriebenen) Namen, mit Kategorie und Ladentyp.
    static func nonFoodMatch(forLowercased nameLower: String) -> (keyword: String, category: String, storeGroup: String?)? {
        var best: (keyword: String, category: String, storeGroup: String?)?
        for entry in nonFoodCategoryMap {
            for keyword in entry.keywords where nameLower.contains(keyword) {
                if best == nil || keyword.count > best!.keyword.count {
                    best = (keyword, entry.category, entry.storeGroup)
                }
            }
        }
        return best
    }

    /// Kategorie aus der Wortend-Regel, falls eine Endung passt. Vergleicht das letzte Wort des
    /// Namens (Bindestrich-Komposita wie „LED-Lampe“ zählen als ein Wort, Leerzeichen trennen).
    static func nonFoodCategoryByEnding(forLowercased nameLower: String) -> String? {
        let trimmed = nameLower.trimmingCharacters(in: .whitespacesAndNewlines)
        guard let lastWord = trimmed.split(separator: " ").last.map(String.init), lastWord.count >= 4 else { return nil }
        for rule in nonFoodCategoryEndings where lastWord.hasSuffix(rule.ending) && lastWord.count > rule.ending.count {
            return rule.category
        }
        // Ganzes Wort gleich der Endung („Erde“, „Zaun“, „Grill“): nur für Regeln ≥ 4 Zeichen.
        for rule in nonFoodCategoryEndings where lastWord == rule.ending && rule.ending.count >= 4 {
            return rule.category
        }
        return nil
    }

    /// Ladentyp aus der Warenkunde für `assignDetailed`: "drugstore", "hardware" oder "variety", wenn
    /// das längste Stichwort einen bevorzugten Ladentyp nennt; "grocery", wenn ein Eintrag trifft, der
    /// keinen hat (Tierbedarf, Schnittblumen, Lebensmittel-Ausnahmen) — dann entscheidet nicht mehr eine
    /// der alten Stichwortlisten; nil, wenn kein Stichwort trifft oder ein Lebensmittel-Stichwort länger ist.
    static func nonFoodStoreGroup(forLowercased nameLower: String) -> String? {
        guard let nonFood = nonFoodMatch(forLowercased: nameLower) else { return nil }
        if let food = bestFoodMatch(forLowercased: nameLower), food.keyword.count > nonFood.keyword.count {
            return nil
        }
        return nonFood.storeGroup ?? "grocery"
    }

